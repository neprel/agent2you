"""Render a fleet workspace into a runnable deploy tree.

`a2y render` reads fleet.yaml + agents/*/agent.yaml and writes `deploy/`:

    deploy/docker-compose.yaml      one service per agent
    deploy/example.env              every variable the compose file references
    deploy/agents/<name>/           the /config directory mounted into the agent:
        agent.yaml                  identity + ports (read by the entrypoint)
        SOUL.md                     persona + fleet-shared section
        config.yaml                 Hermes
        acp2api.yaml                the ACP bridge and its MCP servers
        litellm.yaml                the failover chain
        hindsight.json              memory profile (when memory is hindsight)
    deploy/banks/*.json             shared bank profiles, copied

The output is deterministic: same manifests, same tree, byte for byte. Commit it —
a reviewable deploy tree is the point of generating instead of hand-writing.

Escape hatch: agents/<name>/overrides/<filename> replaces the generated file
verbatim. Use it when a knob the generator does not expose is needed; prefer
teaching the generator when the need repeats.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import yaml

from .manifest import Agent, Fleet, ManifestError

GENERATED = "# GENERATED by `a2y render` -- edit the manifests, not this file.\n"

# Hermes toolsets that stay off in every agent: third-party keys this pack does
# not assume, surfaces a channel-resident agent has no use for, and everything
# the coding CLI already does better in its own loop (a duplicate is not free --
# every Hermes-side call ends the completion and round-trips through Hermes).
DISABLED_TOOLSETS = [
    "bfl", "browser", "code_execution", "computer_use", "desktop_ui",
    "discord", "discord_admin", "feishu_doc", "feishu_drive", "file",
    "homeassistant", "image_gen", "search", "spotify", "stt", "terminal",
    "todo", "tts", "video", "video_gen", "vision", "web", "x_search", "yuanbao",
]

MATTERMOST_PLUGINS = [
    "mention-on-edit",   # a mention arriving by EDIT wakes nobody upstream
    "untagged-routing",  # exactly one agent claims an untagged human message
    "trace-to-card",     # answer in the post, working trace behind the (i) card
    "reasoning-live",    # live progress bubble while a turn runs
    "steer-into-turn",   # /steer lands INSIDE the running ACP turn
]


def _dump(data: dict, header: str = GENERATED) -> str:
    return header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


def _executor_entry(name: str, spec: dict, mcp: list[dict]) -> dict:
    """One entry in acp2api's `agents:` list."""
    kind = spec.get("kind") or name
    entry: dict = {"name": name}
    if kind == "claude":
        entry["type"] = "claude"
        # bypassPermissions is refused under root without IS_SANDBOX=1, and the
        # containers run as root; acceptEdits costs nothing on top of
        # `permission: allow` and does not fail at session setup.
        entry["mode"] = spec.get("mode", "acceptEdits")
    elif kind == "codex":
        entry["type"] = "codex"
        # codex-acp sends a sandboxPolicy per TURN from the ACP session mode;
        # bubblewrap cannot work inside these containers, so the default mode
        # costs a failed first attempt on every command. config.toml does not fix
        # this; the session mode does.
        entry["mode"] = spec.get("mode", "agent-full-access")
    elif kind == "opencode":
        entry["type"] = "general"
        entry["command"] = "opencode"
        entry["args"] = ["acp"]
    elif kind == "cline":
        entry["type"] = "general"
        entry["command"] = "cline"
        entry["args"] = ["--acp"]
    elif kind == "custom":
        entry["type"] = "general"
        entry["command"] = spec["command"]
        if spec.get("args"):
            entry["args"] = list(spec["args"])
    if spec.get("model"):
        entry["model"] = spec["model"]
    if spec.get("reasoning"):
        entry["reasoning"] = spec["reasoning"]
    if spec.get("env"):
        entry["env"] = dict(spec["env"])
    if spec.get("account"):
        # Which subscription this executor spends. Declared, not discovered: it
        # is a property of the login volume, and no ACP message reports it.
        entry["labels"] = {"account": spec["account"]}
    entry["mcpServers"] = mcp
    return entry


def _mcp_servers(agent: Agent) -> list[dict]:
    """The default MCP set for one agent, plus its manifest extras.

    These go in acp2api.yaml, INSIDE the ACP session -- the cheap route. Tools
    routed through Hermes' `tools` array end the completion on every call.
    """
    fleet = agent.fleet
    servers: list[dict] = [
        {
            # Hermes' own bridge: read-only cross-thread history, skills, events.
            # stdio only; finds $HERMES_HOME from $HOME on its own.
            "name": "hermes",
            "type": "stdio",
            "command": "/opt/agent/hermes-agent/venv/bin/hermes",
            "args": ["mcp", "serve"],
        }
    ]
    if fleet.platform_kind == "mattermost":
        for tool in ("boards", "playbooks"):
            if agent.raw.get("tools", {}).get(tool, True):
                servers.append({
                    # A stdio sidecar reusing THIS container's MATTERMOST_TOKEN:
                    # the agent's reach is exactly its own account's reach.
                    "name": tool,
                    "type": "stdio",
                    "command": f"mattermost-{tool}-mcp",
                    "args": ["--url", "${MATTERMOST_URL}", "--token", "${MATTERMOST_TOKEN}",
                             "--team", "${MATTERMOST_TEAM}"],
                })
    if fleet.memory_kind == "hindsight":
        url = str(fleet.memory["url"]).rstrip("/")
        if agent.memory.get("personal", True):
            servers.append({
                "name": "memory-own",
                "url": f"{url}/mcp/agent-{agent.name}/",
                "headers": {"Authorization": "Bearer ${HINDSIGHT_API_KEY}"},
            })
        for project in agent.project_banks():
            servers.append({
                # Shared bank: tools-only on purpose -- a bank several agents
                # read should be written deliberately, not as a side effect.
                "name": f"memory-{project}",
                "url": f"{url}/mcp/project-{project}/",
                "headers": {"Authorization": "Bearer ${HINDSIGHT_API_KEY}"},
            })
    if fleet.observability.get("phoenix_url"):
        servers.append({
            # The fleet's own traces as tools. Command is `phoenix-mcp` (npm
            # strips the scope); the URL goes in as a flag because the package
            # reads several env names. No `env:` here on purpose -- ACP `env`
            # REPLACES the child environment and node vanishes from PATH.
            "name": "traces",
            "type": "stdio",
            "command": "phoenix-mcp",
            "args": ["--baseUrl", "${PHOENIX_URL}"],
        })
    servers.extend(agent.extra_mcp)
    return servers


def render_acp2api(agent: Agent) -> str:
    ports = agent.ports()
    server = {
        "host": "127.0.0.1",
        "port": "${ACP2API_PORT}",
        # Set by the entrypoint: a fixed bind in bridge mode, a discovered one in
        # shared-namespace mode, "off" when nothing scrapes.
        "metricsAddr": "${ACP2API_METRICS_ADDR:-off}",
        "cwd": "/work",
        "fs": True,
        "terminal": False,       # advertised-but-ignored by Claude Code; measured
        "permission": "allow",   # nobody is at a keyboard; /work bounds the blast radius
        "progress": "reasoning",
        "progressOutputLines": 6,
        "commentary": "trace",
        "busy": "queue",         # lets a steered message join the RUNNING turn
        "requestTimeoutMs": 900000,
        "continuity": True,
        "maxSessions": 20,
        "sessionTtlMs": 1800000,
        "forgetTtlMs": 86400000,
        "maxContextFill": 0.85,
    }
    server.update(agent.raw.get("acp2api") or {})
    _ = ports  # ports land in agent.yaml; acp2api reads its own from the env
    mcp = _mcp_servers(agent)
    agents = [_executor_entry(n, agent.executors[n], mcp) for n in agent.chain
              if (agent.executors[n].get("kind") or n) != "openai"]
    return _dump({"server": server, "agents": agents})


def render_litellm(agent: Agent) -> str:
    model_list = []
    fallback_names = []
    for i, name in enumerate(agent.chain):
        spec = agent.executors[name]
        kind = spec.get("kind") or name
        model_name = "brain" if i == 0 else f"brain-{name}"
        fallback_names.append(model_name)
        if kind == "openai":
            params = {
                "model": f"openai/{spec.get('model', 'default')}",
                "api_base": spec["base_url"],
                "api_key": f"os.environ/{spec.get('api_key_env', 'OPENAI_API_KEY')}",
                "timeout": 900,
            }
        else:
            params = {
                "model": f"openai/{name}",
                "api_base": "os.environ/ACP2API_BASE_URL",
                # acp2api has no auth (loopback); litellm still wants a word.
                "api_key": "none-required",
                "timeout": 900,
                # An ACP agent answers in prose; response_format 400s. Hermes
                # sends it for titling, so it must be dropped by name here.
                "additional_drop_params": ["response_format"],
            }
        model_list.append({"model_name": model_name, "litellm_params": params})
    data = {
        "model_list": model_list,
        "litellm_settings": {
            # Absorb params the transport cannot carry (reasoning_effort et al).
            "drop_params": True,
            # 429 from acp2api means a SPENT subscription -- retrying the same
            # model burns time to reach the same answer; the chain is the retry.
            "num_retries": 0,
            "request_timeout": 900,
            "cache": False,
        },
        "general_settings": {
            "master_key": "os.environ/LITELLM_MASTER_KEY",
            # Without this the x-conversation-id header dies here and every
            # message opens a COLD coding agent.
            "forward_client_headers_to_llm_api": True,
        },
    }
    if len(fallback_names) > 1:
        data["litellm_settings"]["fallbacks"] = [{"brain": fallback_names[1:]}]
    return _dump(data)


def render_hermes_config(agent: Agent) -> str:
    fleet = agent.fleet
    plugins = ["conversation-key"]
    if fleet.platform_kind == "mattermost":
        plugins += MATTERMOST_PLUGINS
    if fleet.observability.get("phoenix_url"):
        plugins.append("hermes_otel")

    # Where Hermes' one model actually points follows the topology:
    #   litellm on            -> the chain, behind litellm
    #   single ACP brain      -> straight at acp2api (no litellm to run)
    #   single openai brain   -> straight at the endpoint (neither process)
    if agent.litellm_enabled:
        model_block = {
            "provider": "custom",
            "default": "brain",
            "base_url": "${LITELLM_BASE_URL}",
            # MUST be explicit: `provider: custom` does not fall back to
            # OPENAI_API_KEY -- Hermes sends the literal `no-key-required` and
            # litellm reports it as "No connected db.", which reads as a broken
            # proxy rather than bad auth.
            "api_key": "${LITELLM_MASTER_KEY}",
        }
    elif agent.acp2api_enabled:
        model_block = {
            "provider": "custom",
            "default": agent.chain[0],
            "base_url": "${ACP2API_BASE_URL}",
            # acp2api has no auth (loopback); Hermes still wants a word.
            "api_key": "none-required",
        }
    else:
        spec = agent.executors[agent.chain[0]]
        model_block = {
            "provider": "custom",
            "default": spec["model"],
            "base_url": spec["base_url"],
            "api_key": f"${{{spec['api_key_env']}}}" if spec.get("api_key_env") else "none-required",
        }
    data: dict = {
        "model": model_block,
        "agent": {
            "max_turns": 90,
            "verbose": False,
            "disabled_toolsets": list(DISABLED_TOOLSETS),
        },
        "terminal": {"backend": "local", "cwd": "/work", "timeout": 600},
        "group_sessions_per_user": False,
        "session_reset": {"mode": "none"},
        "compression": {"enabled": False},
        "streaming": {"enabled": False},
        "display": {
            "busy_input_mode": "steer",
            "show_reasoning": True,
            "reasoning_style": "blockquote",
            "tool_progress_grouping": "accumulate",
            "cleanup_progress": True,
        },
        "onboarding": {"seen": {"busy_input_prompt": True, "tool_progress_prompt": True}},
        "auxiliary": {"title_generation": {"enabled": False}},
        "gateway": {"platforms": {"a2a": {"enabled": True}}},
        "plugins": {"enabled": plugins},
        "telemetry": {"shared_metrics": {"enabled": False}},
    }
    if fleet.platform_kind == "mattermost":
        data["platform_toolsets"] = {"mattermost": ["hermes-mattermost"]}
        # Three display settings are DISCARDED on Mattermost unless the platform
        # repeats them (require_platform_override_for) -- silently, with the
        # top-level value still sitting in the file looking correct.
        data["display"]["platforms"] = {
            "mattermost": {"show_reasoning": True, "thinking_progress": True}
        }
    if fleet.memory_kind == "hindsight" and agent.memory.get("personal", True):
        data["memory"] = {
            "provider": "hindsight",
            "memory_enabled": True,
            "user_profile_enabled": True,
        }
    hermes_over = agent.raw.get("hermes") or {}
    if hermes_over:
        from .manifest import _deep_merge  # local import to keep module API small
        data = _deep_merge(data, hermes_over)
    return _dump(data)


def render_agent_yaml(agent: Agent) -> str:
    """The runtime identity file the entrypoint reads (and /fleet roster scans).

    Only the ports of components this agent actually runs appear here -- the
    entrypoint and supervisord assemble the process list from exactly this."""
    ports = agent.ports()
    port_map: dict = {"a2a": ports["a2a"]}
    if agent.acp2api_enabled:
        port_map["acp2api"] = ports["acp2api"]
    if agent.litellm_enabled:
        port_map["litellm"] = ports["litellm"]
    data: dict = {
        "name": agent.name,
        "description": agent.description,
        "ports": port_map,
    }
    if agent.fleet.platform_kind == "mattermost":
        data["mattermost"] = {
            "reply_mode": agent.platform.get("reply_mode", "thread"),
            "require_mention": agent.platform.get("require_mention", True),
        }
    if agent.fleet.memory_kind == "hindsight":
        data["memory"] = {"mode": "local_external", "url": agent.fleet.memory["url"]}
    return _dump(data)


DEFAULT_RETAIN_MISSION = (
    "Keep durable facts about this work and how the operator wants it run. Skip transient "
    "state -- ids, one-off command output, anything that stops being true when the task ends. "
    "Extract the FEWEST facts that capture the OUTCOME: settled DECISIONS and their exact "
    "rules/values (quote literals VERBATIM); problems and how they were resolved; conventions "
    "established. CRITICAL: a conversation REVISES itself -- record ONLY the FINAL state as "
    "what is in effect. NEVER record what the AGENT did, offered, confirmed or will do next. "
    "Record what the OPERATOR wants, decides and repeats. NEVER record general knowledge, "
    "definitions, or explanations."
)

DEFAULT_OBSERVATIONS_MISSION = (
    "Consolidate durable knowledge -- recurring patterns, conventions, responsibilities, and "
    "how components relate. Favor stable structural understanding over one-off details. When a "
    "new fact contradicts or supersedes an existing observation, UPDATE that observation to "
    "reflect the current state rather than creating a sibling; note that the rule was revised "
    "and when. NEVER record what the AGENT did. NEVER record measurements or system state. "
    "NEVER record general knowledge."
)


def render_hindsight(agent: Agent) -> str:
    mem = agent.memory
    data = {
        "mode": "local_external",
        "api_url": agent.fleet.memory["url"],
        "bank_id": f"agent-{agent.name}",
        "bank_mission": mem.get(
            "mission",
            f"The working memory of {agent.name}: {agent.description} What matters: decisions "
            "and the reasoning behind them, what has broken before and why, and the operator's "
            "standing preferences.",
        ),
        "bank_retain_mission": mem.get("retain_mission", DEFAULT_RETAIN_MISSION),
        "bank_observations_mission": mem.get("observations_mission", DEFAULT_OBSERVATIONS_MISSION),
        # `context` keeps automatic injection and drops the duplicate tools --
        # the MCP banks in acp2api.yaml are the deliberate-write route.
        "memory_mode": "context",
        "auto_recall": True,
        "recall_budget": "mid",
        "recall_max_tokens": 4096,
        "auto_retain": mem.get("auto_retain", True),
        "retain_async": True,
        "retain_every_n_turns": 1,
        "retain_context": mem.get(
            "retain_context",
            f"work in a chat channel between the operator and the {agent.name} agent",
        ),
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


